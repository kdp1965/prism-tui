// ==========================================================================
// 80's style synthesizer ('synth' command)
//
// The synth chroma turns the PRISM into a square wave tone generator with
// a 1MHz PWM amplitude DAC on uo_out[7] (the audio PMOD):
//
//   comm     = PWM duty D.  31 = silence, 31 +/- a = volume a/32
//   compare  = 62 (carrier period = 64 clocks = 1MHz)
//   preload  = note half period in clocks (~32e6 / freq)
//
// The FSM raises the interrupt at every phase swap (twice per note
// period).  The CPU can ignore it (steady square wave) or use it to
// alternate two preload values (variable pulse width / PWM sweep) or to
// load LFSR random half periods (noise / percussion).  Volume envelopes,
// vibrato and pulse width sweeps are all just register byte writes.
// ==========================================================================

