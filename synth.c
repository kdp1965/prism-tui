// ==========================================================================
// "Floating Lanterns"
//
// Soothing, handpan / tubular-bell style piece for the PRISM PCM poly synth.
//
// Designed around:
//   - 3 independent ringing voices
//   - ~5 second natural decay
//   - 80 ms sequencer step
//   - notes being allowed to ring into following notes
//
// Tonal center: D major / B minor
//
// Main palette:
//
//      D  E  F#  A  B
//
// Mostly D-major pentatonic.  C# and G appear selectively to establish
// harmony, but close dissonances are intentionally avoided because the
// long ringing tails cause neighbouring notes to overlap.
//
// Harmonic language:
//
//      D(add2) | Bm | G | Asus2 / A
//
// Open voicings are favored:
//
//      Dadd2 : D3 A3 E4
//      D     : D3 A3 F#4
