static const int8_t synth_vib_sin[16] = {
    0, 3, 6, 7, 8, 7, 6, 3, 0, -3, -6, -7, -8, -7, -6, -3
};

// Synth engine state (struct defined in synth.h)
synth_state_t syn;


static const uint8_t synth_duo_iv[]        = { 0, 12, 7, 4 };
static const char *const synth_duo_name[]  = { "off", "octave", "fifth", "third" };
#define NUM_DUO ((int)(sizeof(synth_duo_iv) / sizeof(synth_duo_iv[0])))

// Recompute the preload value(s) from base_p, vibrato and pulse width,
// and stage them for the FSM
static void synth_apply_pitch(void)
{
    uint32_t p = syn.base_p;

    if (syn.pre->vib_depth && syn.gate_ms > syn.pre->vib_delay) {
        int32_t d = (int32_t)(p >> 10) * synth_vib_sin[syn.vib_phase]
                    * syn.pre->vib_depth;
        p += d >> 3;
    }

    if (syn.pre->wave == WAVE_PULSE || syn.pre->wave == WAVE_SWEEP) {
        uint8_t pw = syn.pre->wave == WAVE_SWEEP ? syn.pw_cur : syn.pre->pw;
        uint32_t p2 = p << 1;
        uint32_t ta = (p2 >> 8) * pw;

        if (ta < SYNTH_MIN_HALF)
            ta = SYNTH_MIN_HALF;
        if (ta > p2 - SYNTH_MIN_HALF)
            ta = p2 - SYNTH_MIN_HALF;
        syn.t_a = ta;
        syn.t_b = p2 - ta;
    } else {
        syn.t_a = syn.t_b = p;
    }

    // Stage for the next phase swap; the alternation between t_a and t_b
    // is kept up by the interrupt polling in the main loop.  The flute
    // voice keeps the FSM oscillator running at the plain note period,
    // and the laser dive rewrites it every ms.
    if (syn.pre->wave == WAVE_SQUARE || syn.pre->wave == WAVE_FLUTE ||
            syn.pre->wave == WAVE_LASER)
        prism_write32(PRISM_REG_PRELOAD, p);
}

// Change pitch without retriggering the envelope (arpeggios, slides)
static void synth_set_pitch(int semi, int oct)
{
    if (oct < 1)  oct = 1;
    if (oct > 8)  oct = 8;
    syn.base_p = note_scaled(synth_note_p[semi] >> (oct - 1));
    syn.pitch_target = syn.base_p;
    synth_apply_pitch();
}

// Set the arpeggiator cycle: base plus up to two intervals packed as
// nibbles (lo first, 0 = unused).  ms = 0 selects the default chip rate.
void synth_set_arp(uint8_t base, uint8_t intervals, uint8_t ms)
{
    syn.arp_note[0] = base;
    syn.arp_n = 1;
    if (intervals & 0xF)
        syn.arp_note[syn.arp_n++] = base + (intervals & 0xF);
    if (intervals >> 4)
        syn.arp_note[syn.arp_n++] = base + (intervals >> 4);
    syn.arp_ms = ms ? ms : SYNTH_ARP_MS;
    syn.arp_idx = 0;
    syn.arp_tmr = 0;
}

void synth_note_on(int semi, int oct)
{
    syn.env_state = ENV_ATTACK;
    syn.gate_ms = 0;
    syn.vib_phase = 0;
    syn.vib_div = 0;
    // Live keyboard duo mode; the demo sequencer overrides this with the
    // event's own arp setting right after
    synth_set_arp((uint8_t)(oct * 12 + semi), synth_duo_iv[syn.duo],
                  SYNTH_DUO_MS);
    synth_set_pitch(semi, oct);
    // Flute notes scoop up into pitch: start ~3% flat and glide in
    if (syn.pre->wave == WAVE_FLUTE) {
        syn.base_p += syn.base_p >> 5;
        synth_apply_pitch();
    }
    // Make sure the very next swap picks up the new pitch
    prism_write32(PRISM_REG_PRELOAD, syn.t_a);
    note_out("%s%d ", synth_note_name[semi], oct);
}

void synth_note_off(void)
{
    if (syn.env_state != ENV_IDLE && syn.env_state != ENV_RELEASE)
        syn.env_state = ENV_RELEASE;
}

// Flute voice.  A shakuhachi style tone is mostly a sine, which a square
// wave synth can't play - but the FSM flips output polarity at every
// phase swap anyway, so if the amplitude traces a half-sine lobe between
// swaps (resynced by the swap interrupt), the filtered output IS a sine.
// Breath comes from LFSR noise mixed into the amplitude, strongest during
// the attack; the pitch scoop and the deep delayed vibrato do the rest.
static const uint8_t synth_halfsine[16] = {
    25, 74, 120, 162, 198, 226, 245, 254,
    254, 245, 226, 198, 162, 120, 74, 25
};

static void synth_flute_service(void)
{
    uint32_t now = read_time();

    // Phase swap: the FSM just started the opposite lobe - restart ours
    if (prism_read32(PRISM_REG_CTRL) & PRISM_CTRL_INTERRUPT) {
        prism_write8(PRISM_REG_HOST_TOGGLE, SYNTH_M);
        syn.flute_step = 0;
        syn.flute_next = now;
    }

    if ((int32_t)(now - syn.flute_next) < 0)
        return;
    // 16 amplitude samples per half period: base_p/64MHz/16 = base_p>>10 us
    syn.flute_next = now + (syn.base_p >> 10);

    if (syn.env_state == ENV_IDLE) {
        prism_comm_write(SYNTH_CENTER);
        return;
    }

    uint16_t amp16 = (uint16_t)(syn.level >> 7) * syn.vel16;        // 0..480
    int a = ((int)synth_halfsine[syn.flute_step] * amp16) >> 12;    // 0..29
    if (syn.flute_step < 15)
        ++syn.flute_step;       // hold near zero until the swap resyncs

    // Breath: a whisper of noise always, a strong burst while the note
    // starts (the shakuhachi attack "chiff")
    int breath = 1 + (syn.gate_ms < 128 ? (int)((128 - syn.gate_ms) >> 4) : 0);
    syn.lfsr = (syn.lfsr >> 1) ^ (-(syn.lfsr & 1) & 0xB400);
    a += (((int)(syn.lfsr & 15) - 8) * breath) >> 3;

    if (a < 0)  a = 0;
    if (a > 30) a = 30;
    prism_comm_write((uint8_t)(SYNTH_CENTER + a));
}

// Phase swap interrupt service: keep the pulse width alternation (or the
// noise generator) fed.  The host-toggle write clears the interrupt and
// rewrites the carrier period in one access.
void synth_service(void)
{
    if (syn.pre->wave == WAVE_FLUTE) {
        synth_flute_service();
        return;
    }

    if (syn.pre->wave == WAVE_SQUARE || syn.pre->wave == WAVE_LASER ||
            !(prism_read32(PRISM_REG_CTRL) & PRISM_CTRL_INTERRUPT))
        return;

    uint32_t p;

    if (WAVE_IS_NOISE(syn.pre->wave)) {
        syn.lfsr = (syn.lfsr >> 1) ^ (-(syn.lfsr & 1) & 0xB400);
        p = (syn.base_p >> 5) +
            (((syn.base_p >> 5) * (uint32_t)(syn.lfsr & 0xFF)) >> 6);
    } else {
        syn.swap_phase ^= 1;
        p = syn.swap_phase ? syn.t_b : syn.t_a;
    }
    prism_write32(PRISM_REG_PRELOAD, p);
    prism_write8(PRISM_REG_HOST_TOGGLE, SYNTH_M);
}

// 1ms housekeeping: envelope -> comm (volume), vibrato and PWM sweep
void synth_tick(void)
{
    const synth_preset_t *pre = syn.pre;
    int pitch_dirty = 0;

    if (syn.gate_ms < 0xFFFF)
        ++syn.gate_ms;

    switch (syn.env_state) {
    case ENV_ATTACK:
        if (pre->attack == 0 || syn.level + pre->attack >= SYNTH_LVL_MAX) {
            syn.level = SYNTH_LVL_MAX;
            syn.env_state = ENV_DECAY;
        } else
            syn.level += pre->attack;
        break;
    case ENV_DECAY:
        if (syn.level > pre->sustain + pre->decay)
            syn.level -= pre->decay;
        else {
            syn.level = pre->sustain;
            // sustain 0 marks a one-shot (bell, drum, effects): done
            syn.env_state = pre->sustain ? ENV_SUSTAIN : ENV_IDLE;
        }
        break;
    case ENV_RELEASE:
        if (syn.level > pre->release)
            syn.level -= pre->release;
        else {
            syn.level = 0;
            syn.env_state = ENV_IDLE;
        }
        break;
    default:
        break;
    }

    // The flute voice owns the comm register (it shapes it per sample)
    if (pre->wave != WAVE_FLUTE)
        prism_comm_write(SYNTH_CENTER + (((syn.level >> 7) * syn.vel16) >> 4));

    // Sound effect pitch sweeps: the laser dives (and needs the preload
    // rewritten); the gun crack and explosion darken their noise, which
    // the swap interrupt service picks up from base_p by itself
    if (syn.env_state != ENV_IDLE &&
            (pre->wave == WAVE_LASER || WAVE_IS_NOISE(pre->wave)) &&
            pre->pw && syn.base_p < 4000000u) {
        syn.base_p += syn.base_p >> pre->pw;
        if (pre->wave == WAVE_LASER)
            pitch_dirty = 1;
    }

    // Flute pitch scoop: glide base_p down onto the target pitch
    if (pre->wave == WAVE_FLUTE && syn.base_p > syn.pitch_target) {
        uint32_t d = syn.base_p - syn.pitch_target;
        d = (d >> 5) + 1;
        syn.base_p = syn.base_p - d < syn.pitch_target ?
                     syn.pitch_target : syn.base_p - d;
        pitch_dirty = 1;
    }

    // Arpeggiator / duophony: rotate the sounding pitch through the cycle
    if (syn.arp_n > 1 && syn.env_state != ENV_IDLE &&
            ++syn.arp_tmr >= syn.arp_ms) {
        syn.arp_tmr = 0;
        if (++syn.arp_idx >= syn.arp_n)
            syn.arp_idx = 0;
        uint8_t n = syn.arp_note[syn.arp_idx];
        synth_set_pitch(n % 12, n / 12);
    }

    if (pre->vib_depth && syn.env_state != ENV_IDLE &&
            syn.gate_ms > pre->vib_delay) {
        if (++syn.vib_div >= pre->vib_rate) {
            syn.vib_div = 0;
            syn.vib_phase = (syn.vib_phase + 1) & 15;
            pitch_dirty = 1;
        }
    }

    if (pre->wave == WAVE_SWEEP && syn.env_state != ENV_IDLE) {
        syn.pw_cur += syn.pw_dir;
        if (syn.pw_cur >= 216)
            syn.pw_dir = -1;
        else if (syn.pw_cur <= 40)
            syn.pw_dir = 1;
        pitch_dirty = 1;
    }

    if (pitch_dirty)
        synth_apply_pitch();
}

static void synth_show_preset(void)
{
    note_out("[%s] ", syn.pre->name);
}

static int synth_key(int c)
{
    for (int i = 0; synth_keys_lo[i]; ++i)
        if (c == synth_keys_lo[i]) {
            synth_note_on(i, syn.octave);
            return 1;
        }
    for (int i = 0; synth_keys_hi[i]; ++i)
        if (c == synth_keys_hi[i]) {
            synth_note_on(i, syn.octave + 1);
            return 1;
        }

    switch (c) {
    case 'i':
        synth_note_on(0, syn.octave + 2);
        return 1;
    case ' ':
        synth_note_off();
        return 0;
    case '-':
        if (syn.octave > 1)
            --syn.octave;
        note_out("oct%d ", syn.octave);
        return 0;
    case '=':
        if (syn.octave < 6)
            ++syn.octave;
        note_out("oct%d ", syn.octave);
        return 0;
    case 'k':
        syn.duo = (uint8_t)((syn.duo + 1) % NUM_DUO);
        note_out("duo:%s ", synth_duo_name[syn.duo]);
        // Re-shape the sounding note with the new interval
        synth_set_arp(syn.arp_note[0], synth_duo_iv[syn.duo], SYNTH_DUO_MS);
        return 0;
    case 'o':
        syn.preset_idx = (syn.preset_idx + NUM_PRESETS - 1) % NUM_PRESETS;
        break;
    case 'p':
        syn.preset_idx = (syn.preset_idx + 1) % NUM_PRESETS;
        break;
    default:
        return 0;
    }

    // Preset changed
    syn.pre = &synth_presets[syn.preset_idx];
    synth_show_preset();
    if (syn.env_state != ENV_IDLE)
        synth_apply_pitch();
    return 0;
}
// Load the synth chroma and set up the engine.  Returns 0 on success.
static int synth_init(void)
{
    printf("\nLoading synth Chroma\n");

    // Stage sane register values first so the FSM starts up at the
    // pin's idle level (the fade after load brings it to silence)
    prism_set_count2_compare(SYNTH_M);
    prism_comm_write(1);
    prism_set_count1_preload(note_scaled(synth_note_p[0] >> 3)); // parked at C4

    int res = prism_load_chroma(chroma_synth, CHROMA_SYNTH_CTRL);

    chroma_set_loaded(chroma_synth);
    if (res) {
        printf("load FAILED, error mask 0x%05x\n", res);
        return res;
    }
    // fade the carrier up from the pin's idle level: no turn-on pop
    for (int d = 1; d <= SYNTH_CENTER; ++d) {
        prism_comm_write((uint8_t)d);
        uint32_t t0 = read_time();
        while (read_time() - t0 < us_ticks(300))
            ;
    }
    chroma_set_loaded(chroma_synth);

    prism_disable_interrupt();      // we poll; no ISR wanted
    prism_clear_interrupt();

    // Route the audio PMOD pin (uo_out[7]) to the PRISM
    set_gpio_func(7, 8);

    memset(&syn, 0, sizeof(syn));
    syn.preset_idx = 0;
    syn.pre = &synth_presets[0];
    syn.octave = 3;
    syn.pw_dir = 1;
    syn.pw_cur = 128;
    syn.lfsr = 0xACE1;
    syn.vel16 = 16;
    return 0;
}

void cmd_synth(int argc, char *argv[])
{
    if (argc > 1 && !strcmp(argv[1], "demo")) {
        uint32_t which = 1;
        if (argc > 2 && !parse_u32(argv[2], &which))
            return;
        if (which < 1 || which > (uint32_t)synth_demo_count()) {
            printf("demos:");
            for (int i = 0; i < synth_demo_count(); ++i)
                printf(" %d = %s%s", i + 1, synth_demo_name(i),
                       i < synth_demo_count() - 1 ? "," : "\n");
            return;
        }
        if (synth_init())
            return;
        synth_demo((int)which);
        prism_disable();
        return;
    }

    if (synth_init())
        return;

    printf(
"~~~ PRISM synth ~~~\n"
"  keys:  z s x d c v g b h n j m   = C..B (octave %d)\n"
"         q 2 w 3 e r 5 t 6 y 7 u   = C..B (octave %d), i = C%d\n"
"  - / =  octave down / up      o / p  previous / next preset\n"
"  k      duo mode (rapidly alternated 2nd voice: off/octave/fifth/third)\n"
"  space  release note          ESC or ` quits\n"
"  presets: ", syn.octave, syn.octave + 1, syn.octave + 2);
    for (int i = 0; i < NUM_PRESETS; ++i)
        printf("%s ", synth_presets[i].name);
    printf("\n\n");
    synth_show_preset();

    uint32_t next_tick = read_time() + us_ticks(1000);

    for (;;) {
        int c = uart_getc();

        if (c == 0x1b || c == '`')
            break;
        if (c != -1)
            synth_key(c);

        synth_service();

        if ((int32_t)(read_time() - next_tick) >= 0) {
            next_tick += us_ticks(1000);
            synth_tick();
        }
    }

    for (int d = SYNTH_CENTER; d >= 1; --d) {   // fade out, no pop
        prism_comm_write((uint8_t)d);
        uint32_t t0 = read_time();
        while (read_time() - t0 < us_ticks(300))
            ;
    }
    prism_disable();        // resets the FSM: output low, silent
    printf("\nsynth off\n");
}

// ==========================================================================
// Polyphonic PWL synth ('synthp' command), in the spirit of the
// PiecewiseOrionSynth peripheral: three voices with piecewise linear
// waveforms (saw / triangle), a shift-based brightness control that acts
// like the PWL slope (clamped scaling morphs towards square = brighter),
// and per-voice decay envelopes, all summed in software at 15625Hz and
// played through the PCM chroma's 8-bit PWM DAC (prism_isr.s mode 2, same
// ping-pong machinery as ADPCM playback).  Budget: ~70 instructions per
// sample against a 65.5ms buffer budget - it fits at 64MHz.
// ==========================================================================

#define POLY_VOICES     4               // 4th voice only at >=85MHz
int poly_nvoices = 3;
int poly_drum_voice = -1;   // the MIDI player reserves the last voice
                            // for the kit when the song has drums
#define POLY_BLOCK      1024u           // samples per ping-pong buffer
#define POLY_RATE       12500u          // internal render rate the note
                                        //   step table is referenced to
#define POLY_OUT_HZ     25000u          // 2x-interpolated OUTPUT rate

// 'synthp -i': the renderer computes 12500Hz samples but the output
// stream runs at double rate with a linear-interpolated midpoint
// between each pair, pushing the zero-order-hold images from ~12.3kHz
// (audible whistles) to ~25kHz (ultrasonic).  Off (default) streams
// the rendered samples directly at ~12.5kHz.
int poly_interp;

// Clocks per OUTPUT sample: nearest whole number of 256-clock
// carriers (same rule as the ADPCM player).  At 64MHz both modes are
// exact: 2560 clocks (25000Hz) / 5120 clocks (12500Hz).
static uint32_t poly_out_period(void)
{
    uint32_t rate = poly_interp ? POLY_OUT_HZ : POLY_RATE;
    uint32_t period = (clock_hz + rate / 2) / rate;

    return ((period + 128u) / 256u) * 256u;
}

// count1 preload (the FSM adds its 64-clock offset back)
static uint32_t poly_preload(void)
{
    return poly_out_period() - 64u;
}

// Q16 note-step correction: the grid-rounded output rate makes the
// REAL internal rate clock_hz/(2*period) instead of 12500; scaling
// each note's step by 12500/internal cancels it exactly, so absolute
// pitch is spot on at ANY clock (identity, 65536, at 64MHz).
static uint32_t poly_step_scale = 65536u;

struct poly_voice {
    uint32_t phase;
    uint32_t step;                      // frequency as phase/sample
    uint8_t  level;                     // envelope 0..31
    int8_t   ramp;                      // +1 attack / -1 release, one level
                                        //   per 8 samples (~20ms 0..full):
                                        //   soft edges, no speaker pop
    uint8_t  decay_div;
    uint8_t  vocal;                     // melody voice: protected from
                                        //   accompaniment stealing
    uint8_t  inst;                      // instrument (poly_presets index)
    uint16_t lfsr;                      // noise state (tri == 2 presets)
    uint8_t  peak;                      // velocity peak level 24..31
    uint16_t gate;                      // chunks until auto note-off (0 off)
    uint32_t step_tgt;                  // real pitch (slide/vibrato center)
    int32_t  slide_inc;                 // pitch env: step delta per chunk
    uint16_t slide_n;                   // chunks of slide left
    uint16_t vib_wait;                  // chunks before the LFO starts
    int32_t  vib_pos, vib_inc, vib_dev; // triangle LFO state (step units)
};

typedef struct {
    const char *name;
    uint8_t tri;                        // 0 = saw, 1 = tri, 2 = LFSR noise
    uint8_t bright;                     // clamp-morph shift 0..3
    // amp ADSR on the 31-level ladder (~3dB per level):
    uint8_t a_mask;                     // attack: 2^k-1 samples per level
    uint8_t decay;                      // decay: chunks (5.1ms) per level
    uint8_t sus;                        // sustain level (0 = ring out)
    uint8_t r_mask;                     // release samples-per-level mask
    uint16_t gate_ms;                   // auto note-off (0 = hold/ring)
    // pitch envelope: start p_off semitones away, slide home over
    // p_ms8*8 ms (PWL-style scoop/grace)
    int8_t  p_off;
    uint8_t p_ms8;
    // vibrato triangle LFO: the held-note modulator
    uint8_t v_rate;                     // Hz*2
    uint8_t v_cents;                    // peak deviation (0 = off)
    uint16_t v_delay_ms;                // onset delay
} poly_preset_t;

