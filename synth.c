// Note-progression sink (see synth.h): NULL = plain printf to console.
// The TUI points this at its Notes tab while it is on screen.
int (*synth_note_out)(const char *fmt, ...);

// Chroma bitstream generated by the PRISM Yosys backend (chroma_synth.v,
// tinyqv.cfg).  Square wave tone generator with a 1MHz PWM amplitude DAC
// on uo_out[7]: comm = duty (volume), compare = 62 (carrier period 64),
// preload = note half period in clocks.  Interrupt on each phase swap.
const uint32_t chroma_synth[PRISM_CHROMA_WORDS*2] = {
    0x000003d4, 0x00008000,
    0x000002ba, 0x00800015,
    0x000002a4, 0x02c0c016,
    0x00000296, 0x0280a01e,
    0x000003d6, 0x00000000,
    0x000002b8, 0x00c08015,
    0x000002a4, 0x02804016,
    0x00000294, 0x02c0201e,
};
// CHROMA_SYNTH_CTRL is in prism_tui.h

// Note half periods for octave 1 (32e6/freq - 32, centering the 64-clock
// carrier grid rounding).  Octave n is a right shift by n-1.
// Scale a 64MHz-referenced half period to the real clock (the -32
// carrier-grid centering is in fixed 64-clock carriers, so it is
// removed, scaled, and re-applied)
static uint32_t note_scaled(uint32_t p)
{
    if (clock_hz == 64000000u)
        return p;
    return (uint32_t)(((uint64_t)(p + 32) * clock_hz) / 64000000u) - 32;
}

