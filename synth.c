static void pdemo_fire(void)
{
    if (pdemo_ev->n[0] == PD_DAMP) {
        for (int nv = 0; nv < poly_nvoices; ++nv) {
            if (poly_v[nv].level)
                poly_v[nv].ramp = -1;   // organist lifts hands: soft release
            poly_v[nv].vocal = 0;       // melody protection ends too
        }
        return;
    }
    for (int i = 0; i < 3; ++i) {
        uint8_t n = pdemo_ev->n[i];
        if (n)
            poly_note_on_ex((n & 0x7F) % 12, (n & 0x7F) / 12,
                            (n & PD_V) != 0,
                            (n & PD_V) ? 127 : 100, poly_preset);
    }
}

// Fade the PCM chroma's carrier duty between 'pin low' and mid-scale
// silence over ~10ms, so starting and stopping the synth doesn't step the
// speaker by half the supply (the same pop the note ramps fix, one layer
// down)
static void pcm_carrier_fade(int up)
{
    for (int d = up ? 1 : 127; up ? d <= 127 : d >= 1; d += up ? 2 : -2) {
        prism_set_count2_compare((uint8_t)d);
        uint32_t t0 = read_time();
        while (read_time() - t0 < us_ticks(150))
            ;
    }
}

static uint32_t pe_refill, pe_underruns, pe_max_us, pe_blocks, pe_bb;

// Bring the whole poly output chain up: PCM chroma, carrier, sample
// clock, primed ping-pong buffers, ISR streaming.  Shared by the
// keyboard/demo command and the MIDI player.
int poly_engine_start(void)
{
    printf("\nLoading PCM Chroma for the poly synth\n");

    prism_comm_write(254);                      // carrier period
    prism_set_count2_compare(1);                // start at the pin's idle
    prism_set_count1_preload(poly_preload());
    poly_step_scale = (uint32_t)((((uint64_t)(poly_interp ? POLY_OUT_HZ
                                               : POLY_RATE)
                                   * poly_out_period()) << 16) / clock_hz);
    if (poly_interp)
        printf("2x interpolated output\n");

    int res = prism_load_chroma(chroma_pcm, CHROMA_PCM_CTRL);

    chroma_set_loaded(chroma_pcm);
    if (res) {
        printf("load FAILED, error mask 0x%05x\n", res);
        return -1;
    }
    chroma_set_loaded(chroma_pcm);
    prism_disable_interrupt();
    prism_clear_interrupt();
    set_gpio_func(7, 8);

    pcm_carrier_fade(1);                        // ease up to mid scale

    poly_nvoices = clock_hz >= 85000000u ? 4 : 3;
    poly_drum_voice = -1;
    memset(poly_v, 0, sizeof(poly_v));
    memset(poly_buf, 128, sizeof(poly_buf));

    // Prime both buffers, then let the ISR stream them (mode 2)
    poly_render(poly_buf[0]);
    poly_render(poly_buf[1]);
    pe_bb = (poly_interp ? 2u : 1u) * POLY_BLOCK;         // block bytes

    l4z_ch.rd = (uint32_t *)(void *)poly_buf[0];
    l4z_ch.end = (uint32_t *)(void *)(poly_buf[0] + pe_bb);
    l4z_ch.next = (uint32_t *)(void *)poly_buf[1];
    l4z_ch.next_end = (uint32_t *)(void *)(poly_buf[1] + pe_bb);
    l4z_ch.consumed = 0;
    l4z_ch.active = 2;
    prism_enable_interrupt();

    pe_refill = pe_underruns = pe_max_us = pe_blocks = 0;
    return 0;
}

// One pass of refill housekeeping; returns nonzero when a buffer was
// rendered (the caller's idle loop needs no other pacing)
int poly_engine_service(void)
{
    if (!l4z_ch.consumed)
        return 0;
    l4z_ch.consumed = 0;
    uint32_t t0 = read_time();
    poly_render(poly_buf[pe_refill]);
    l4z_ch.next = (uint32_t *)(void *)poly_buf[pe_refill];
    l4z_ch.next_end = (uint32_t *)(void *)(poly_buf[pe_refill] + pe_bb);
    pe_refill ^= 1;
    uint32_t dt = read_time() - t0;
    if (dt > pe_max_us)
        pe_max_us = dt;
    if (l4z_ch.consumed)
        ++pe_underruns;
    ++pe_blocks;
    return 1;
}

void poly_engine_stop(void)
{
    l4z_ch.active = 0;
    prism_disable_interrupt();
    prism_clear_interrupt();
    pcm_carrier_fade(0);                // ease back down before the cut
    prism_disable();

    printf("\n%lu blocks, %lu underruns, max render %luus"
           " (budget %luus per buffer)\n",
           (unsigned long)pe_blocks, (unsigned long)pe_underruns,
           (unsigned long)(((uint64_t)pe_max_us * 64000000u) / clock_hz),
           (unsigned long)(((uint64_t)pe_bb * poly_out_period()
                            * 1000000u) / clock_hz));
}

void cmd_synthp(int argc, char *argv[])
{
    // '-i' anywhere: 2x interpolated output (A/B against the plain
    // 12.5kHz stream)
    poly_interp = 0;
    for (int a = 1; a < argc; a++)
        if (!strcmp(argv[a], "-i")) {
            poly_interp = 1;
            for (int b = a; b < argc - 1; b++)
                argv[b] = argv[b + 1];
            argc--;
            a--;
        }

    // The interpolated stream only fits the refill budget with the
    // 85MHz block time: at 64MHz the doubled ISR rate + 2048-byte
    // PSRAM emit measured 81.8ms against the 81.9ms budget (demo 2
    // underruns = the popping) - refuse rather than crackle.
    if (poly_interp && clock_hz < 85000000u) {
        printf("-i needs the 85MHz clock (run --freq 85) - playing plain\n");
        poly_interp = 0;
    }

    int demo = argc > 1 && !strcmp(argv[1], "demo");
    uint32_t which = 1;

    if (demo && argc > 2 && (!parse_u32(argv[2], &which) ||
                             which < 1 || which > (uint32_t)NUM_PDEMOS)) {
        printf("poly demos:");
        for (int i = 0; i < NUM_PDEMOS; ++i)
            printf(" %d = %s%s", i + 1, pdemo_songs[i].name,
                   i < NUM_PDEMOS - 1 ? "," : "\n");
        return;
    }

    if (poly_engine_start() != 0)
        return;
    poly_preset = 0;
    syn.octave = 3;

    if (demo) {
        poly_preset = PDEMO_PRESET;
        pdemo_song = pdemo_songs[which - 1].song;
        pdemo_ev = pdemo_song;
        printf("~~~ poly synth demo: %s ~~~  (any key stops)\n\n[%s] ",
               pdemo_songs[which - 1].name,
               poly_presets[poly_preset].name);
    } else {
        printf(
"~~~ PRISM poly synth (3 voices) ~~~\n"
"  same keyboard as 'synth'; chords ring while you play more notes\n"
"  o / p  instrument   - / =  octave   space  silence all   ESC quits\n"
"  instruments: ");
        for (int i = 0; i < NUM_POLY_PRESETS; ++i)
            printf("%s ", poly_presets[i].name);
        printf("\n\n[%s] ", poly_presets[poly_preset].name);
    }



    if (demo) {
        pdemo_next = read_time();       // first event fires immediately
    }

    int demo_done = 0;                  // last demo event fired; ring out

    for (;;) {
        int c = uart_getc();

        if (demo) {
            if (c != -1)                // any key stops the demo
                break;
            if (!demo_done &&
                (int32_t)(read_time() - pdemo_next) >= 0) {
                pdemo_fire();
                pdemo_next += us_ticks((uint32_t)pdemo_ev->len * PDEMO_STEP_US);
                ++pdemo_ev;
                if (pdemo_ev->len == 0)
                    demo_done = 1;      // no loop - let the last notes ring
            }
            if (demo_done && !poly_active())
                break;                  // song finished: back to the prompt
        } else {
            if (c == 0x1b || c == '`')
                break;
            if (c != -1)
                poly_key(c);
        }

        poly_engine_service();
    }

    poly_engine_stop();
    printf("synthp off\n");
}
