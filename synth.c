// Envelope scaling without multiplies: a uniform ~3dB ladder (6dB shift
// per two levels, x0.75 half-steps between)
static inline int32_t poly_env(int32_t v, uint32_t lv)
{
    uint32_t a = 31 - lv;

    v >>= a >> 1;
    if (a & 1)
        v -= v >> 2;
    return v;
}

// Render one buffer of summed voices; returns nonzero if any voice is
// sounding.  Voice-major: each voice's state stays in registers for the
// whole block (struct accesses per sample were the previous version's
// downfall - 101ms per block; this one fits the budget), sweeping a mix
// buffer that a final pass converts to PWM duty bytes.
static int32_t poly_mix[POLY_BLOCK];

static uint32_t poly_render(uint8_t *dst)
{
    int wrote = 0;

    for (int nv = 0; nv < poly_nvoices; ++nv) {
        struct poly_voice *v = &poly_v[nv];

        if (!v->level && !v->ramp)
            continue;
        // Envelope rates and waveform come from the VOICE's instrument,
        // so a MIDI melody, bass and drums can sound at once
        const poly_preset_t *pre = &poly_presets[v->inst];
        const int tri = pre->tri == 1;
        const int noise = pre->tri == 2;
        const int bright = pre->bright;
        const uint32_t decay = pre->decay;
        uint32_t lfsr = v->lfsr ? v->lfsr : 0xACE1u;
        uint32_t phase = v->phase, step = v->step;
        uint32_t lv = v->level, div = v->decay_div;
        uint32_t peak = v->peak ? v->peak : 31u;
        uint32_t sus = pre->sus;
        int32_t *mp = poly_mix;

        int32_t ramp = v->ramp;
        // Attack/release stepping rates come from the instrument (2^k-1
        // samples per ladder level); attacks still SPEAK, but a pad can
        // now swell and a release can linger.
        uint32_t rmask = (ramp > 0) ? pre->a_mask : pre->r_mask;

        for (uint32_t chunk = 0; chunk < POLY_BLOCK / 64; ++chunk, mp += 64) {
            if (!lv && !ramp) {         // idle / released
                if (!wrote)
                    memset(mp, 0, 64 * sizeof(*mp));
                continue;
            }
            // Chunk-rate modulators (5.1ms): pitch slide home, then the
            // vibrato triangle around the landed pitch, and the gate
            // clock that turns note-on into a timed note-off.
            if (v->slide_n) {
                step += (uint32_t)v->slide_inc;
                if (!--v->slide_n)
                    step = v->step_tgt;
            } else if (v->vib_dev) {
                if (v->vib_wait)
                    --v->vib_wait;
                else {
                    v->vib_pos += v->vib_inc;
                    if (v->vib_pos > v->vib_dev || v->vib_pos < -v->vib_dev) {
                        v->vib_inc = -v->vib_inc;
                        v->vib_pos += 2 * v->vib_inc;
                    }
                    step = (uint32_t)((int32_t)v->step_tgt + v->vib_pos);
                }
            }
            if (v->gate && !--v->gate) {
                ramp = -1;              // gate elapsed: release stage
                rmask = pre->r_mask;
            }
            if (ramp) {
                // attack or release stepping, rate set by rmask above
                for (uint32_t i = 0; i < 64; ++i) {
                    phase += step;
                    int32_t s;
                    if (noise) {
                        lfsr = (lfsr >> 1) ^ ((0u - (lfsr & 1u)) & 0xB400u);
                        s = (int16_t)lfsr;
                    } else {
                        s = (int32_t)(phase >> 16) - 32768;
                        if (tri) {
                            int32_t a = s >> 31;
                            s = 32767 - (((s ^ a) - a) << 1);
                        }
                        s <<= bright;
                        if (s > 32767) s = 32767;
                        else if (s < -32768) s = -32768;
                    }
                    s = poly_env(s, lv);
                    if (wrote)
                        mp[i] += s;
                    else
                        mp[i] = s;
                    if ((i & rmask) == rmask) {
                        int32_t nl = (int32_t)lv + ramp;
                        if (ramp > 0 && nl >= (int32_t)peak) {
                            lv = peak; ramp = 0;
                        }
                        else if (nl <= 0) { lv = 0; ramp = 0; }
                        else lv = (uint32_t)nl;
                    }
                }
            } else {
                for (uint32_t i = 0; i < 64; ++i) {
                    phase += step;
                    int32_t s;
                    if (noise) {                                    // drums
                        lfsr = (lfsr >> 1) ^ ((0u - (lfsr & 1u)) & 0xB400u);
                        s = (int16_t)lfsr;
                    } else {
                    s = (int32_t)(phase >> 16) - 32768;             // saw
                    if (tri) {
                        int32_t a = s >> 31;                        // triangle
                        s = 32767 - (((s ^ a) - a) << 1);
                    }
                    s <<= bright;                                   // PWL slope
                    if (s > 32767) s = 32767;                       // clamp
                    else if (s < -32768) s = -32768;
                    }
                    s = poly_env(s, lv);
                    if (wrote)
                        mp[i] += s;
                    else
                        mp[i] = s;
                }
                if (++div >= decay) {   // decay toward sustain, per
                    div = 0;                // chunk (sus 0 = ring out)
                    if (lv > sus)
                        --lv;
                }
            }
        }
        v->phase = phase;
        v->step = step;                 // slides advance it per chunk
        v->lfsr = (uint16_t)lfsr;
        v->level = (uint8_t)lv;
        v->ramp = (int8_t)ramp;
        v->decay_div = (uint8_t)div;
        wrote = 1;
    }

    static int32_t last = 128;          // previous block's final duty,
                                        //   for the seam midpoint
    if (!wrote) {
        memset(dst, 128, (poly_interp ? 2u : 1u) * POLY_BLOCK);
        last = 128;
        return 0;
    }
    // The output buffers live in PSRAM where every store is a bus
    // transaction (~us each, not ns) - at 64MHz the interpolated
    // byte-by-byte emit alone cost more than the refill slack and
    // popped audibly (83.1ms render vs the 81.9ms budget, 153
    // underruns in 15s of demo 2).  Packing four duty bytes per
    // 32-bit store cuts those transactions 4x; dst is 4-aligned and
    // POLY_BLOCK a multiple of 4.
    uint32_t *wd = (uint32_t *)(void *)dst;

    if (!poly_interp) {
        for (uint32_t i = 0; i < POLY_BLOCK; i += 4) {
            uint32_t w = 0;

            for (uint32_t k = 0; k < 4; ++k) {
                int32_t d = 128 + (poly_mix[i + k] >> 10);

                if (d < 1) d = 1;
                else if (d > 253) d = 253;
                w |= (uint32_t)d << (8 * k);
            }
            *wd++ = w;
        }
        return 1;
    }
    for (uint32_t i = 0; i < POLY_BLOCK; i += 2) {
        int32_t d0 = 128 + (poly_mix[i] >> 10);
        int32_t d1 = 128 + (poly_mix[i + 1] >> 10);

        if (d0 < 1) d0 = 1;
        else if (d0 > 253) d0 = 253;
        if (d1 < 1) d1 = 1;
        else if (d1 > 253) d1 = 253;
        *wd++ = (uint32_t)((last + d0) >> 1)            // midpoints
              | ((uint32_t)d0 << 8)
              | ((uint32_t)((d0 + d1) >> 1) << 16)
              | ((uint32_t)d1 << 24);
        last = d1;
    }
    return 1;
}

int poly_note_on_ex(int semi, int oct, int vocal, int vel, int inst)
{
    if (oct < 1) oct = 1;
    if (oct > 6) oct = 6;                       // keep under Nyquist

    // phase step: f / 12500 in 32.32; with P = 32e6/f this is exactly
    // (2560 << 32) / P
    // RAW 64MHz-referenced half period: poly_step_scale maps the step
    // to the real internal rate on its own - note_scaled() here too
    // was double clock scaling (-5 semitones at 85MHz)
    uint32_t p = synth_note_p[semi] >> (oct - 1);

    // Voice selection with melody protection (PD_V):
    //   1. an idle voice
    //   2. the quietest accompaniment voice (smallest cut, musically
    //      the most decayed note)
    //   3. vocal notes only: the quietest vocal voice
    // An accompaniment strike never steals a still-ringing vocal voice;
    // with none available it is dropped so the melody holds its full
    // length.  At most two voices stay vocal at once (a new melody note
    // then recycles the older melody line) so accompaniment always has
    // at least one voice to cycle through.
    struct poly_voice *idle = NULL, *acc = NULL, *voc = NULL;
    struct poly_voice *v;
    int nvoc = 0;

    if (poly_drum_voice >= 0 && inst >= POLY_I_KICK) {
        v = &poly_v[poly_drum_voice];   // the kit owns its voice: a hit
        goto take;                      // simply replaces what rings
    }
    for (int nv = 0; nv < poly_nvoices; ++nv) {
        struct poly_voice *c = &poly_v[nv];

        if (nv == poly_drum_voice)
            continue;                   // reserved for the kit
        if (!c->level) {                // idle (render zeroes ramp too)
            if (idle == NULL)
                idle = c;
        } else if (c->vocal) {
            ++nvoc;
            if (voc == NULL || c->level < voc->level)
                voc = c;
        } else {
            if (acc == NULL || c->level < acc->level)
                acc = c;
        }
    }
    if (vocal && nvoc >= 2)
        v = voc;                        // recycle the older melody line
    else if (idle != NULL)
        v = idle;
    else if (acc != NULL)
        v = acc;
    else if (vocal)
        v = voc;
    else
        return -1;                      // all voices vocal: drop accomp.
take:
    v->vocal = (uint8_t)vocal;
    v->inst = (uint8_t)inst;

    v->step = (uint32_t)((2560ULL << 32) / p);
    v->step = (uint32_t)(((uint64_t)v->step * poly_step_scale) >> 16);
    v->step_tgt = v->step;

    // Instrument modulators (all chunk-rate; ~205/1024 chunks per ms)
    const poly_preset_t *in = &poly_presets[inst];

    v->slide_n = 0;
    v->vib_dev = 0;
    v->vib_pos = 0;
    if (in->p_off) {                    // scoop/grace: start offset
        int s2 = semi + in->p_off, o2 = oct;

        while (s2 < 0)   { s2 += 12; --o2; }
        while (s2 >= 12) { s2 -= 12; ++o2; }
        if (o2 < 1) o2 = 1;
        if (o2 > 6) o2 = 6;
        uint32_t p2 = synth_note_p[s2] >> (o2 - 1);
        uint32_t st = (uint32_t)((2560ULL << 32) / p2);
        uint32_t n = ((uint32_t)in->p_ms8 * 8u * 205u) >> 10;

        st = (uint32_t)(((uint64_t)st * poly_step_scale) >> 16);
        if (n == 0)
            n = 1;
        v->slide_inc = (int32_t)(v->step_tgt - st) / (int32_t)n;
        v->slide_n = (uint16_t)n;
        v->step = st;
    }
    if (in->v_cents) {                  // vibrato: dev in step units,
        v->vib_dev = (int32_t)(((uint64_t)v->step_tgt * in->v_cents)
                               / 1731u);
        v->vib_inc = (int32_t)(((int64_t)v->vib_dev * in->v_rate) / 98);
        if (v->vib_inc == 0)
            v->vib_inc = 1;
        v->vib_wait = (uint16_t)(((uint32_t)in->v_delay_ms * 205u) >> 10);
    }
    v->gate = (uint16_t)(((uint32_t)in->gate_ms * 205u) >> 10);
    v->peak = (uint8_t)(31u - ((127u - ((uint32_t)vel & 127u)) >> 4));
    // start at the waveform's zero crossing so the first samples are
    // near silent and the soft attack does the rest
    v->phase = in->tri ? 0x40000000u : 0x80000000u;
    // Skip the inaudible bottom of the ladder (levels 1..11 are below
    // -60dB): starting at 12 plus the 2-sample attack rate puts the
    // note at full level in ~3ms instead of ~20ms, so the organ speaks
    // on the beat.  The zero-crossing phase start keeps the onset
    // pop-free even at this rate.
    v->level = 12;
    v->ramp = 1;                        // ~3ms attack (see rmask)
    v->decay_div = 0;
    // Melody (PD_V) notes print in bright yellow: raw ANSI on the plain
    // console; the TUI's Notes tab translates the same escapes into
    // curses attributes at draw time.
    {
        char tok[8];

        if (inst == POLY_I_KICK)
            tok[0] = 'K', tok[1] = 0;
        else if (inst == POLY_I_SNARE)
            tok[0] = 'S', tok[1] = 0;
        else if (inst == POLY_I_HAT)
            tok[0] = 'H', tok[1] = 0;
        else
            snprintf(tok, sizeof(tok), "%s%d", synth_note_name[semi], oct);
        if (poly_note_out2)             // TUI voice tracks
            poly_note_out2((int)(v - poly_v), tok);
        else if (vocal)
            note_out("\x1b[93m%s\x1b[0m ", tok);
        else
            note_out("%s ", tok);
    }
    return (int)(v - poly_v);
}

void poly_voice_gate(int vi, uint32_t ms)
{
    if (vi >= 0 && vi < poly_nvoices)
        poly_v[vi].gate = (uint16_t)((ms * 205u) >> 10);
}

int poly_active(void)
{
    for (int nv = 0; nv < poly_nvoices; ++nv)
        if (poly_v[nv].level || poly_v[nv].ramp)
            return 1;
    return 0;
}

static void poly_note_on(int semi, int oct)
{
    poly_note_on_ex(semi, oct, 0, 118, poly_preset);
}

static int poly_key(int c)
{
    for (int i = 0; synth_keys_lo[i]; ++i)
        if (c == synth_keys_lo[i]) {
            poly_note_on(i, syn.octave);
            return 1;
        }
    for (int i = 0; synth_keys_hi[i]; ++i)
        if (c == synth_keys_hi[i]) {
            poly_note_on(i, syn.octave + 1);
            return 1;
        }

    switch (c) {
    case '-':
        if (syn.octave > 1) --syn.octave;
        note_out("oct%d ", syn.octave);
        break;
    case '=':
        if (syn.octave < 5) ++syn.octave;
        note_out("oct%d ", syn.octave);
        break;
    case ' ':
        for (int nv = 0; nv < poly_nvoices; ++nv)
            if (poly_v[nv].level)
                poly_v[nv].ramp = -1;   // soft release, no pop
        break;
    case 'o':
        poly_preset = (poly_preset + NUM_POLY_PRESETS - 1) % NUM_POLY_PRESETS;
        note_out("[%s] ", poly_presets[poly_preset].name);
        break;
    case 'p':
        poly_preset = (poly_preset + 1) % NUM_POLY_PRESETS;
        note_out("[%s] ", poly_presets[poly_preset].name);
        break;
    }
    return 0;
}

